import { chromium } from "playwright"
const b=await chromium.launch({executablePath:"/usr/bin/google-chrome",args:["--no-sandbox","--disable-dev-shm-usage"]})
const ctx=await b.newContext({viewport:{width:1440,height:1000}})
const p=await ctx.newPage()
const bad=[]
p.on("response",r=>{ if(r.status()>=400) bad.push(`${r.status()} ${r.request().method()} ${r.url().slice(0,110)}`) })
await p.goto("https://marsbgc.ir/product/catan",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(1500)
await p.locator("button",{hasText:"افزودن به سبد"}).first().click()
await p.waitForTimeout(2000)
const modal = await p.evaluate(()=>document.body.innerText.includes("به سبد اضافه شد") || !!document.querySelector(".sf-atc, [role=dialog]"))
console.log("ADD_MODAL:", modal)
await p.goto("https://marsbgc.ir/cart",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(1500)
const cart = await p.evaluate(()=>({ txt:document.body.innerText.replace(/\s+/g," ").slice(0,300), qtyInput: !!document.querySelector("input[type=number], input[inputmode=numeric]") }))
console.log("CART:", JSON.stringify(cart))
await p.goto("https://marsbgc.ir/checkout",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(2000)
const co = await p.evaluate(()=>({ url:location.pathname, txt:document.body.innerText.replace(/\s+/g," ").slice(0,300) }))
console.log("CHECKOUT:", JSON.stringify(co))
console.log("BAD:", JSON.stringify([...new Set(bad)].slice(0,8)))
await b.close()
