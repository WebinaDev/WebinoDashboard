import { chromium } from "playwright"
const b=await chromium.launch({executablePath:"/usr/bin/google-chrome",args:["--no-sandbox","--disable-dev-shm-usage"]})
const p=await (await b.newContext({viewport:{width:1440,height:1000}})).newPage()
await p.goto("https://marsbgc.ir/login",{waitUntil:"networkidle",timeout:45000})
await p.fill('input[type="email"]',"qa-checkout@marsbgc.ir")
await p.fill('input[type="password"]',"QaTest!2026")
await p.locator('button[type="submit"], form button').first().click()
await p.waitForTimeout(5000)
console.log("URL:", p.url())
const t = await p.evaluate(()=>document.body.innerText.replace(/\s+/g," ").slice(0,600))
console.log("DASH:", t)
await p.goto("https://marsbgc.ir/account",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(2000)
console.log("ACCOUNT:", await p.evaluate(()=>document.body.innerText.replace(/\s+/g," ").slice(0,400)))
await b.close()
