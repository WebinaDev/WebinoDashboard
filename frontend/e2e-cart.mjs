import { chromium } from "playwright"
const b=await chromium.launch({executablePath:"/usr/bin/google-chrome",args:["--no-sandbox","--disable-dev-shm-usage"]})
const ctx=await b.newContext({viewport:{width:1440,height:1000}})
const p=await ctx.newPage()
const errs=[]; p.on("console",m=>{if(m.type()==="error")errs.push(m.text().slice(0,160))}); p.on("pageerror",e=>errs.push("PE:"+String(e).slice(0,160)))
await p.goto("https://marsbgc.ir/shop",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(1500)
// click first add-to-cart
const btn = p.locator("button", {hasText:"افزودن به سبد"}).first()
console.log("addbtns", await p.locator("button", {hasText:"افزودن به سبد"}).count())
await btn.click()
await p.waitForTimeout(2500)
console.log("after add url:", p.url())
console.log("modal text:", (await p.locator("body").innerText()).match(/به سبد اضافه شد[\s\S]{0,120}/)?.[0])
await p.goto("https://marsbgc.ir/cart",{waitUntil:"networkidle",timeout:45000})
await p.waitForTimeout(1500)
const txt = await p.locator("body").innerText()
console.log("CART:", txt.replace(/\s+/g," ").slice(0,500))
console.log("errors:", [...new Set(errs)].slice(0,6))
await b.close()
