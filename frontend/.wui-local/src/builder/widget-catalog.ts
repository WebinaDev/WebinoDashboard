/** Resolve a widget's catalog entry; unknown module-prefixed keys fall into their module category. */
export function catalogEntry(type: string): CatalogEntry {
  if (Object.prototype.hasOwnProperty.call(WIDGET_CATALOG, type)) return WIDGET_CATALOG[type]
  if (type.startsWith("resume-")) return { category: "resume", icon: "FileUser" }
  if (type.startsWith("cafe-")) return { category: "cafe", icon: "Coffee" }
  if (type.startsWith("academy-")) return { category: "academy", icon: "GraduationCap" }
  if (type.startsWith("webina-")) return { category: "webina", icon: "Sparkle" }
  if (type.startsWith("poe")) return { category: "poetry", icon: "Feather" }
  return { category: "other", icon: "Blocks" }
}

/** Group widget defs by catalog category (category order kept, empty groups dropped). */
export function groupWidgetsByCatalog<T extends { type: string }>(widgets: readonly T[]): { category: CatalogCategory; widgets: T[] }[] {
  return WIDGET_CATALOG_CATEGORIES.map((category) => ({ category, widgets: widgets.filter((w) => catalogEntry(w.type).category === category.id) })).filter((g) => g.widgets.length > 0)
}

/** Every lucide icon name the catalog can return (for building a static icon import map). */
export function catalogIconNames(): string[] {
  return Array.from(new Set([...WIDGET_CATALOG_CATEGORIES.map((c) => c.icon), ...Object.values(WIDGET_CATALOG).map((e) => e.icon), "FileUser", "Coffee", "GraduationCap", "Sparkle", "Feather", "Blocks"]))
}
