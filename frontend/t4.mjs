import { chromium } from "playwright"
const b = await chromium.launch({ executablePath: "/usr/bin/google-chrome", args: ["--no-sandbox"] })
const p = await (await b.newContext({ viewport: { width: 1440, height: 1000 } })).newPage()
await p.goto("https://alikhabari.ir/", { waitUntil: "domcontentloaded", timeout: 90000 })
await p.waitForTimeout(4000)
await p.evaluate(() => document.querySelector(".wpv-hl").scrollIntoView({ block: "center" }))
await p.waitForTimeout(500)
const before = await p.evaluate(() => document.querySelector(".wpv-hl .wpv-track").scrollLeft)
await p.locator('.wpv-hl .wpz-carrow[aria-label="بعدی"]').click()
await p.waitForTimeout(1200)
const afterNext = await p.evaluate(() => document.querySelector(".wpv-hl .wpv-track").scrollLeft)
await p.locator('.wpv-hl .wpz-carrow[aria-label="قبلی"]').click()
await p.waitForTimeout(1200)
const afterPrev = await p.evaluate(() => document.querySelector(".wpv-hl .wpv-track").scrollLeft)
const arrows = await p.evaluate(() => [...document.querySelectorAll(".wpv-hl .wpz-carrow")].map(b => ({ l: b.getAttribute("aria-label"), x: Math.round(b.getBoundingClientRect().x), ic: b.querySelector("svg").getAttribute("class").split(" ")[1] })))
console.log(JSON.stringify({ before, afterNext, afterPrev, arrows }))
await b.close()
